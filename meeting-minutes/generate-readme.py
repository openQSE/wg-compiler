#!/usr/bin/env python3
"""Regenerate README.md in this directory from files named YYYY-MM-DD-*.

Per meeting (date prefix):
  YYYY-MM-DD-title.txt        line 1: meeting title; line 2 (optional): presenter
  YYYY-MM-DD-youtube.txt      first line is the YouTube URL
  YYYY-MM-DD-transcript.docx  transcript
  YYYY-MM-DD-summary.md       summary
  YYYY-MM-DD-<anything>.pdf   slides (also .html, .pptx, .key); .html links via GitHub Pages
"""

import re
from pathlib import Path
from urllib.parse import quote

RAW_BASE = "https://raw.githubusercontent.com/openQSE/wg-compiler/main/meeting-minutes/"
PAGES_BASE = "https://openqse.org/wg-compiler/meeting-minutes/"
SLIDE_EXTS = {".pdf", ".html", ".pptx", ".key"}
DATE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-(.+)$")

here = Path(__file__).resolve().parent

meetings = {}
for f in sorted(here.iterdir()):
    m = DATE_RE.match(f.name)
    if not m or not f.is_file():
        continue
    date, rest = m.groups()
    entry = meetings.setdefault(
        date, {"title": None, "video": None, "slides": [], "transcript": None, "summary": None}
    )
    if rest == "title.txt":
        lines = [ln.strip().replace("|", "\\|") for ln in f.read_text().splitlines() if ln.strip()]
        if lines:
            entry["title"] = lines[0] + (f"<br>*{lines[1]}*" if len(lines) > 1 else "")
    elif rest == "youtube.txt":
        lines = f.read_text().strip().splitlines()
        entry["video"] = lines[0].strip() if lines else None
    elif rest == "transcript.docx":
        entry["transcript"] = f.name
    elif rest == "summary.md":
        entry["summary"] = f.name
    elif f.suffix.lower() in SLIDE_EXTS:
        entry["slides"].append(f.name)


def cell_slides(names):
    # Raw GitHub serves HTML as text, so HTML slides go through GitHub Pages.
    return "<br>".join(
        f"[{n}]({(PAGES_BASE if n.lower().endswith('.html') else RAW_BASE)}{quote(n)})"
        for n in names
    )


rows = []
for date in sorted(meetings):
    e = meetings[date]
    video = f"[YouTube]({e['video']})" if e["video"] else ""
    transcript = f"[Transcript]({RAW_BASE}{quote(e['transcript'])})" if e["transcript"] else ""
    summary = f"[Summary]({quote(e['summary'])})" if e["summary"] else ""
    rows.append(
        f"| {date} | {e['title'] or ''} | {video} | {cell_slides(e['slides'])} | {transcript} | {summary} |"
    )

out = [
    "# Meeting Minutes",
    "",
    "<!-- Generated by generate-readme.py; do not edit by hand. -->",
    "",
    "| Date | Title | Video | Slides | Transcript | Summary |",
    "|------|-------|-------|--------|------------|---------|",
    *rows,
    "",
]
(here / "README.md").write_text("\n".join(out))
print(f"Wrote README.md with {len(rows)} meetings")
